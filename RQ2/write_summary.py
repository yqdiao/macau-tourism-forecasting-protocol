"""Write RQ2 markdown summary with key checks."""
from __future__ import annotations
from pathlib import Path
import pandas as pd
from common import OUT, TABLES, LOGS, RAW, ensure_dirs, log

def run():
    ensure_dirs()
    lines = ["# RQ2 verification summary\n\n"]
    lines.append("Generated by `RQ2/`. Numbers come from sealed prediction records.\n\n")
    cov = pd.read_csv(LOGS / "panel_coverage_check.csv")
    lines.append("## Panel coverage\n\n")
    lines.append("```\n"+cov.to_string(index=False)+"\n```\n\n")
    chk = pd.read_csv(LOGS / "rq1_reopen_mase_check.csv")
    lines.append("## Check against RQ1 reopening MASE\n\n")
    lines.append(f"Max absolute difference = {chk.abs_diff.max():.6g}\n\n")
    lines.append("```\n"+chk.to_string(index=False)+"\n```\n\n")
    for name in sorted(TABLES.glob("table_S*.csv")):
        df = pd.read_csv(name)
        lines.append(f"## {name.name}\n\n")
        lines.append(f"rows={len(df)} cols={df.shape[1]}\n\n")
        lines.append("```\n"+df.head(20).to_string(index=False)+"\n```\n\n")
    if (RAW / "s4_market_decomposition_detail.csv").exists():
        dec = pd.read_csv(RAW / "s4_market_decomposition_detail.csv")
        lines.append("## Market contribution totals (should be ≈100)\n\n")
        for (split, a, b), part in dec.groupby(["split_name", "model_a", "model_b"]):
            lines.append(
                f"- {split} {a}-{b}: MASE share sum={part.share_MASE_pct.sum():.4f}, "
                f"MAE share sum={part.share_MAE_pct.sum():.4f}\n"
            )
    md = OUT / "RQ2_verification_summary.md"
    md.write_text("".join(lines), encoding="utf-8")
    log(f"wrote {md}")

if __name__ == "__main__":
    run()
